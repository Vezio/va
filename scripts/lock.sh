#!/usr/bin/env bash
# lock.sh: pin the runner image's third-party dependencies, with hashes.
#
#   scripts/lock.sh
#
# Resolves the runtime extras (s3, yaml) for the image's platform and Python version and writes
# container/requirements.lock. container/Containerfile installs from it with --require-hashes,
# which keeps rebuilds reproducible and rejects packages whose hashes do not match. Rerun after
# changing an extra and review the resulting diff. Requires uv (preferred) or pip-tools.
set -euo pipefail
cd "$(dirname "$0")/.."
platform="${LOCK_PLATFORM:-x86_64-manylinux_2_28}"
python="${LOCK_PYTHON:-3.12}"
# va and the tool are installed from source with --no-deps; container/requirements.in lists
# the remaining dependencies.
input=container/requirements.in
header="# Generated by scripts/lock.sh for ${platform}, Python ${python}. Do not edit by hand."
if command -v uv >/dev/null; then
  uv pip compile "$input" --generate-hashes --python-version "$python" \
    --python-platform "$platform" --no-header --quiet -o container/requirements.lock.tmp
else
  pip-compile "$input" --generate-hashes --no-header --quiet -o container/requirements.lock.tmp
  echo "lock.sh: pip-tools resolves for this machine, not $platform; prefer uv" >&2
fi
{ echo "$header"; cat container/requirements.lock.tmp; } > container/requirements.lock
rm container/requirements.lock.tmp
echo "wrote container/requirements.lock ($(grep -c '==' container/requirements.lock) pinned packages)"
